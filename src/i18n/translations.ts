export type TranslationKey = keyof typeof BASE_UZ;

export const TRANSLATIONS: Record<Lang, Record<TranslationKey, string>> = {
  uz: BASE_UZ,
  ru: BASE_RU,
  en: BASE_EN,
};

export function t(lang: Lang, key: TranslationKey): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.uz[key];
}

export function formatLocale(lang: Lang): string {
  if (lang === 'ru') return 'ru-RU';
  if (lang === 'en') return 'en-US';
  return 'uz-UZ';
}

export function formatGrade(lang: Lang, grade?: number): string {
  const g = grade || 1;
  if (lang === 'ru') return `${g} класс`;
  if (lang === 'en') return `Grade ${g}`;
  return `${g}-sinf`;
}

export function formatCurrency(lang: Lang, amountUzs: number): string {
  const formatted = amountUzs.toLocaleString(formatLocale(lang));
  if (lang === 'ru') return `${formatted} сум`;
  if (lang === 'en') return `${formatted} UZS`;
  return `${formatted} so‘m`;
}

export function buildGoogleBookSearchUrl(title: string, grade: number, lang: Lang): string {
  const suffix =
    lang === 'ru' ? `${grade} класс учебник pdf` : lang === 'en' ? `grade ${grade} textbook pdf` : `${grade}-sinf darslik pdf`;
  return `https://www.google.com/search?q=${encodeURIComponent(`${title} ${suffix}`)}`;
}
