function build20Questions(
  prefix: string,
  items: Array<{ q: string; opts: [string, string, string, string]; ans: 0 | 1 | 2 | 3; exp: string }>
): TestQuestion[] {
  const result: TestQuestion[] = [];
  for (let i = 0; i < 20; i++) {
    const src = items[i % items.length];
    result.push({
      id: `${prefix}-q-${i + 1}`,
      text: `${i + 1}. ${src.q}`,
      options: src.opts,
      correctIndex: src.ans,
      explanation: src.exp,
    });
  }
  return result;
}

